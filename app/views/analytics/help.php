<section class="analytics-help-grid" aria-label="Bantuan analisis laboratorium">
    <article class="form-section">
        <h2>Filter dan cakupan</h2>
        <p>Semua kartu, grafik, tabel, dan ekspor menggunakan filter yang sama. Periode memakai tanggal pemeriksaan secara inklusif; pasien yang telah diarsipkan tidak ikut dihitung.</p>
    </article>
    <article class="form-section">
        <h2>Pasien unik dan demografi</h2>
        <p>Pasien unik dihitung satu kali. Untuk usia dan jenis kelamin, setiap pasien ditempatkan menurut pemeriksaan terakhirnya dalam periode filter agar jumlah kategori konsisten dengan KPI pasien unik.</p>
    </article>
    <article class="form-section">
        <h2>Hasil abnormal</h2>
        <p>Nilai abnormal adalah hasil yang berada di luar nilai rujukan aktif yang cocok. Hasil tanpa rujukan atau yang tidak dapat diinterpretasi masuk kategori belum dinilai, bukan normal. Ringkasan ini bukan diagnosis.</p>
        <p>ANC ibu hamil memakai rujukan khusus perempuan. Golongan darah dan Rhesus dicatat tanpa penilaian normal/abnormal, sehingga tidak dianggap sebagai hasil yang kekurangan nilai rujukan.</p>
    </article>
    <article class="form-section">
        <h2>Asuransi / penjamin</h2>
        <p>Penjamin diambil dari profil pasien saat dashboard dibuka, bukan snapshot historis pada kunjungan. Nilai kosong selalu ditampilkan sebagai Belum diisi dan tidak disamakan dengan Umum.</p>
    </article>
    <article class="form-section">
        <h2>Kualitas data</h2>
        <p>Indikator draft, identitas kosong, panel belum lengkap, dan hasil tanpa rujukan hanya bersifat informasi. Perbaikan data dilakukan dari halaman pasien, pemeriksaan, atau nilai rujukan terkait.</p>
        <p>Panel otomatis seperti Widal yang seluruh hasilnya masih kosong tidak dihitung sebagai panel belum lengkap. Jika hasilnya mulai diisi, kelengkapannya ikut dihitung.</p>
    </article>
    <article class="form-section">
        <h2>Ekspor agregat</h2>
        <p>Ekspor CSV dan Excel memuat angka agregat yang sama dengan dashboard saat ini beserta filter yang dipakai. Tidak ada nama, nomor rekam medis, NIK, atau identitas pasien dalam ekspor Analisis.</p>
    </article>
</section>

