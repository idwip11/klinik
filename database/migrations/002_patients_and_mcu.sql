CREATE TABLE IF NOT EXISTS patients (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    medical_record_number VARCHAR(50) NOT NULL,
    national_id VARCHAR(32) NULL,
    full_name VARCHAR(150) NOT NULL,
    birth_place VARCHAR(100) NULL,
    birth_date DATE NULL,
    sex ENUM('L', 'P') NULL,
    address TEXT NULL,
    phone VARCHAR(30) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY patients_medical_record_number_unique (medical_record_number),
    UNIQUE KEY patients_national_id_unique (national_id),
    KEY patients_full_name_index (full_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS examinations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    patient_id BIGINT UNSIGNED NOT NULL,
    lab_number VARCHAR(50) NOT NULL,
    examination_type ENUM('mcu_general') NOT NULL DEFAULT 'mcu_general',
    status ENUM('draft', 'completed') NOT NULL DEFAULT 'draft',
    examined_on DATE NOT NULL,
    condition_note VARCHAR(500) NULL,
    letter_number VARCHAR(100) NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    completed_by BIGINT UNSIGNED NULL,
    completed_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY examinations_lab_number_unique (lab_number),
    KEY examinations_patient_date_index (patient_id, examined_on),
    KEY examinations_status_date_index (status, examined_on),
    CONSTRAINT examinations_patient_foreign FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE RESTRICT,
    CONSTRAINT examinations_created_by_foreign FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT examinations_updated_by_foreign FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT examinations_completed_by_foreign FOREIGN KEY (completed_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vital_results (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    examination_id BIGINT UNSIGNED NOT NULL,
    blood_pressure_systolic DECIMAL(6, 0) NULL,
    blood_pressure_diastolic DECIMAL(6, 0) NULL,
    height_cm DECIMAL(6, 2) NULL,
    weight_kg DECIMAL(7, 2) NULL,
    respiratory_rate DECIMAL(6, 0) NULL,
    color_vision VARCHAR(50) NULL,
    pulse_rate DECIMAL(6, 0) NULL,
    blood_group ENUM('A', 'B', 'AB', 'O') NULL,
    rhesus ENUM('+', '-') NULL,
    temperature_c DECIMAL(4, 1) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY vital_results_examination_unique (examination_id),
    CONSTRAINT vital_results_examination_foreign FOREIGN KEY (examination_id) REFERENCES examinations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS blood_results (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    examination_id BIGINT UNSIGNED NOT NULL,
    hgb DECIMAL(7, 2) NULL,
    wbc DECIMAL(12, 2) NULL,
    plt DECIMAL(14, 2) NULL,
    rbc DECIMAL(7, 2) NULL,
    hct DECIMAL(7, 2) NULL,
    gds DECIMAL(8, 2) NULL,
    cholesterol DECIMAL(8, 2) NULL,
    uric_acid DECIMAL(7, 2) NULL,
    sgot DECIMAL(8, 2) NULL,
    sgpt DECIMAL(8, 2) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY blood_results_examination_unique (examination_id),
    CONSTRAINT blood_results_examination_foreign FOREIGN KEY (examination_id) REFERENCES examinations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS urine_results (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    examination_id BIGINT UNSIGNED NOT NULL,
    color VARCHAR(50) NULL,
    clarity VARCHAR(50) NULL,
    specific_gravity DECIMAL(6, 3) NULL,
    ph DECIMAL(4, 1) NULL,
    protein VARCHAR(100) NULL,
    glucose_reduction VARCHAR(100) NULL,
    urobilinogen VARCHAR(100) NULL,
    bilirubin VARCHAR(100) NULL,
    occult_blood VARCHAR(100) NULL,
    ketone VARCHAR(100) NULL,
    nitrite VARCHAR(100) NULL,
    leukocyte_esterase VARCHAR(100) NULL,
    erythrocytes VARCHAR(100) NULL,
    leukocytes VARCHAR(100) NULL,
    squamous_cells VARCHAR(100) NULL,
    casts VARCHAR(100) NULL,
    crystals VARCHAR(100) NULL,
    bacteria VARCHAR(100) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY urine_results_examination_unique (examination_id),
    CONSTRAINT urine_results_examination_foreign FOREIGN KEY (examination_id) REFERENCES examinations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
